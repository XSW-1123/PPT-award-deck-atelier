# -*- coding: utf-8 -*-
"""交付前体检：PPTX 结构 / Morph 转场 / 强制配对 / 旋转角度 / AI 水印 / 元数据。

输出人可读报告；--json 可导出结构化结果。
命中为 0 时**不要**为了「保险」删除任何内容，如实报告即可。

用法：
  python audit_deck.py --pptx deck.pptx
  python audit_deck.py --pptx deck.pptx --images images/ --expect-slides 15 --json report.json
  python audit_deck.py --self-test
"""
from __future__ import annotations

import argparse
import io
import json
import os
import re
import sys
import tempfile
import zipfile

AI_KEYS = [
    'midjourney', 'dall-e', 'stable diffusion', 'sdxl', 'chatgpt', 'copilot',
    'canva', 'gamma.app', 'beautiful.ai', 'tome.app', 'imagen', 'flux.1',
    'made with', 'ai generated', 'generated by ai', 'watermark', 'kling',
    'ai水印', '生成式', 'ai生成', '文心一格', '通义万相', '即梦',
    '对应评分项', '本页得分',
]
PAIR_KEYS = ['!!Stage', '!!DialRotor', '!!Rail']
SLIDE_RE = re.compile(r'ppt/slides/slide(\d+)\.xml$')
TEXT_EXT = ('.xml', '.rels', '.txt', '.json', '.md')


def read_zip(path: str) -> dict[str, bytes]:
    with zipfile.ZipFile(path) as z:
        bad = z.testzip()
        if bad:
            raise ValueError('corrupt zip member: ' + bad)
        return {n: z.read(n) for n in z.namelist()}


def decode(b: bytes) -> str:
    return b.decode('utf-8', errors='ignore')


def check_metadata(files: dict[str, bytes]) -> dict:
    core = decode(files.get('docProps/core.xml', b''))
    app = decode(files.get('docProps/app.xml', b''))
    def field(tag):
        m = re.search(r'<[^>]*%s[^>]*>(.*?)</[^>]*%s>' % (tag, tag), core, re.S | re.I)
        return m.group(1).strip() if m else ''
    return {
        'creator': field('dc:creator'),
        'lastModifiedBy': field('cp:lastModifiedBy'),
        'application': (re.search(r'<Application>(.*?)</Application>', app, re.S) or ['', ''])[1]
        if re.search(r'<Application>(.*?)</Application>', app, re.S) else '',
    }


def check_images(files: dict[str, bytes], images_dir: str | None) -> dict:
    suspicious = []
    try:
        from PIL import Image
    except ImportError:
        return {'checked': 0, 'suspicious': [], 'note': 'Pillow not installed; skipped'}
    targets = [(n, files[n]) for n in files if n.startswith('ppt/media/')]
    if images_dir and os.path.isdir(images_dir):
        for name in os.listdir(images_dir):
            p = os.path.join(images_dir, name)
            if os.path.isfile(p) and name.lower().endswith(('.jpg', '.jpeg', '.png', '.webp')):
                with open(p, 'rb') as fh:
                    targets.append((name, fh.read()))
    for name, blob in targets:
        try:
            im = Image.open(io.BytesIO(blob))
            info = dict(im.info or {})
            exif = {}
            try:
                exif = dict(im.getexif() or {})
            except Exception:
                pass
            text = json.dumps({'info': info, 'exif': exif}, ensure_ascii=False, default=str).lower()
            for k in AI_KEYS:
                if k in text:
                    suspicious.append('%s: %s' % (name, k))
        except Exception:
            continue
    return {'checked': len(targets), 'suspicious': suspicious}


def audit(path: str, images_dir: str | None = None,
          expect_slides: int | None = None) -> dict:
    files = read_zip(path)
    slides = {}
    for n, b in files.items():
        m = SLIDE_RE.match(n)
        if m:
            slides[int(m.group(1))] = decode(b)
    order = sorted(slides)
    xml_all = '\n'.join(decode(b) for n, b in files.items()
                        if n.lower().endswith(TEXT_EXT))
    low = xml_all.lower()
    hits = sorted({k for k in AI_KEYS if k in low})

    morph = sum(1 for x in slides.values() if '<p159:morph' in x or 'effect="morph"' in x)
    fade = sum(1 for x in slides.values() if '<p:fade' in x or ':fade' in x)
    pairs = {k: sum(x.count('name="%s"' % k) for x in slides.values()) for k in PAIR_KEYS}

    rot_angles = []
    for i in order:
        x = slides[i]
        vals = [float(v) / 60000.0 for v in re.findall(r'\brot="(-?\d+)"', x)]
        rotor = re.search(r'name="!!DialRotor"[^>]*>', x)
        if rotor and 'rot=' in rotor.group(0):
            rm = re.search(r'rot="(-?\d+)"', rotor.group(0))
            rot_angles.append(float(rm.group(1)) / 60000.0 if rm else 0.0)
        elif vals:
            rot_angles.append(max(vals, key=abs))
        else:
            rot_angles.append(None)
    known = [a for a in rot_angles if a is not None]
    monotonic = all(known[i] <= known[i + 1] for i in range(len(known) - 1)) if len(known) > 1 else None

    meta = check_metadata(files)
    imgs = check_images(files, images_dir)
    issues = []
    if expect_slides and len(slides) != expect_slides:
        issues.append('slides=%d expected=%d' % (len(slides), expect_slides))
    if morph != len(slides) - 1:
        issues.append('morph=%d expected=%d' % (morph, len(slides) - 1))
    for k, v in pairs.items():
        if v != len(slides):
            issues.append('%s count=%d expected=%d' % (k, v, len(slides)))
    if hits:
        issues.append('AI keyword hits: ' + ', '.join(hits))
    if meta['creator'] or meta['lastModifiedBy']:
        issues.append('core.xml author fields not empty')
    if imgs['suspicious']:
        issues.append('suspicious image metadata: %d' % len(imgs['suspicious']))
    if monotonic is False:
        issues.append('rotor angles are not monotonically increasing')

    return {
        'file': path,
        'bytes': os.path.getsize(path),
        'zip_ok': True,
        'slides': len(slides),
        'morph': morph,
        'fade': fade,
        'pairs': pairs,
        'rotor_angles': rot_angles,
        'rotor_monotonic': monotonic,
        'ai_keyword_hits': hits,
        'core': meta,
        'images': imgs,
        'issues': issues,
        'verdict': 'PASS' if not issues else 'REVIEW',
    }


def self_test() -> int:
    tmp = tempfile.mkdtemp(prefix='atelier_audit_')
    p = os.path.join(tmp, 'tiny.pptx')
    with zipfile.ZipFile(p, 'w') as z:
        z.writestr('docProps/core.xml',
                   '<?xml version="1.0"?><cp:coreProperties>'
                   '<dc:creator></dc:creator><cp:lastModifiedBy></cp:lastModifiedBy>'
                   '</cp:coreProperties>')
        z.writestr('docProps/app.xml',
                   '<?xml version="1.0"?><Properties>'
                   '<Application>Microsoft Office PowerPoint</Application></Properties>')
        for i in range(1, 4):
            tr = '<p:transition><p:fade/></p:transition>' if i == 1 else \
                 '<p:transition><p159:morph option="byObject"/></p:transition>'
            shapes = ''.join('<p:cNvPr name="%s"/>' % k for k in PAIR_KEYS)
            z.writestr('ppt/slides/slide%d.xml' % i,
                       '<p:sld>%s%s<p:spPr rot="%d"/></p:sld>' %
                       (tr, shapes, (i - 1) * 1350000))
    r = audit(p, expect_slides=3)
    assert r['slides'] == 3 and r['morph'] == 2, r
    assert all(v == 3 for v in r['pairs'].values()), r['pairs']
    assert r['ai_keyword_hits'] == [], r['ai_keyword_hits']
    assert r['rotor_monotonic'] is True, r['rotor_angles']
    print('SELFTEST OK: slides=3 morph=2 pairs=3/3/3 rot monotonic, 0 AI hits')
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--pptx')
    ap.add_argument('--images', help='源素材目录，一并扫 EXIF / PNG info')
    ap.add_argument('--expect-slides', type=int)
    ap.add_argument('--json', dest='json_out', help='写结构化报告到该路径')
    ap.add_argument('--self-test', action='store_true')
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if not a.pptx:
        ap.error('--pptx is required unless --self-test')
    r = audit(a.pptx, a.images, a.expect_slides)
    print('file            : %s (%d B)' % (r['file'], r['bytes']))
    print('slides          : %d | morph %d | fade %d' % (r['slides'], r['morph'], r['fade']))
    print('forced pairs    : ' + ', '.join('%s=%d' % (k, v) for k, v in r['pairs'].items()))
    print('rotor angles    : %s | monotonic=%s' % (r['rotor_angles'], r['rotor_monotonic']))
    print('AI keyword hits : %d %s' % (len(r['ai_keyword_hits']), r['ai_keyword_hits']))
    print('core.xml        : creator=%r lastModifiedBy=%r app=%r' %
          (r['core']['creator'], r['core']['lastModifiedBy'], r['core']['application']))
    print('image metadata  : checked=%d suspicious=%d' %
          (r['images']['checked'], len(r['images']['suspicious'])))
    print('verdict         : ' + r['verdict'])
    for i in r['issues']:
        print('  ISSUE ' + i)
    if a.json_out:
        with open(a.json_out, 'w', encoding='utf-8') as fh:
            json.dump(r, fh, ensure_ascii=False, indent=2)
    return 0 if r['verdict'] == 'PASS' else 1


if __name__ == '__main__':
    sys.exit(main())
